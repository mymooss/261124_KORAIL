-- KTX 디지털 트윈 관제 시스템 — Postgres(Supabase) 스키마
-- SQLite 판(schema.sql)과 같은 구조. 시각 문자열은 'YYYY-MM-DD HH24:MI:SS' (Asia/Seoul) 로 저장한다.
-- 앱은 Postgres 에 직접 접속하므로, Supabase REST(anon key)로는 읽히지 않도록 모든 테이블에 RLS 를 켠다.

CREATE TABLE lines (
  id          TEXT PRIMARY KEY,
  name        TEXT NOT NULL,
  color_dark  TEXT NOT NULL,
  color_light TEXT NOT NULL,
  sort_order  INTEGER NOT NULL
);

CREATE TABLE stations (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         TEXT NOT NULL UNIQUE,
  lat          DOUBLE PRECISION NOT NULL,
  lon          DOUBLE PRECISION NOT NULL,
  is_major     INTEGER NOT NULL DEFAULT 0 CHECK (is_major IN (0,1)),
  label_dx     DOUBLE PRECISION NOT NULL DEFAULT 9,
  label_dy     DOUBLE PRECISION NOT NULL DEFAULT 4,
  label_anchor TEXT NOT NULL DEFAULT 'start' CHECK (label_anchor IN ('start','middle','end'))
);

CREATE TABLE line_stations (
  line_id    TEXT NOT NULL REFERENCES lines(id),
  seq        INTEGER NOT NULL,
  station_id BIGINT NOT NULL REFERENCES stations(id),
  PRIMARY KEY (line_id, seq)
);

CREATE TABLE segments (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seg_key       TEXT NOT NULL UNIQUE,
  station_a_id  BIGINT NOT NULL REFERENCES stations(id),
  station_b_id  BIGINT NOT NULL REFERENCES stations(id),
  length_km     DOUBLE PRECISION NOT NULL,
  max_speed_kmh INTEGER NOT NULL DEFAULT 300
);

CREATE TABLE trains (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  train_no       TEXT NOT NULL UNIQUE,
  line_id        TEXT NOT NULL REFERENCES lines(id),
  direction      INTEGER NOT NULL CHECK (direction IN (-1,1)),
  st_idx         INTEGER NOT NULL,
  progress       DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (progress >= 0 AND progress <= 1),
  speed_kmh      DOUBLE PRECISION NOT NULL DEFAULT 0,
  dwell_sec      DOUBLE PRECISION NOT NULL DEFAULT 0,
  delay_min      DOUBLE PRECISION NOT NULL DEFAULT 0,
  status         TEXT NOT NULL DEFAULT '정상운행'
                 CHECK (status IN ('정상운행','주의운행','서행','정차','지연')),
  passengers     INTEGER NOT NULL DEFAULT 500,
  phase_seed     DOUBLE PRECISION NOT NULL DEFAULT 0,
  last_check_sim INTEGER NOT NULL,
  speed_hist     TEXT NOT NULL DEFAULT '[]',
  updated_at     TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'Asia/Seoul', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE train_inspections (
  train_id    BIGINT NOT NULL REFERENCES trains(id) ON DELETE CASCADE,
  item        TEXT NOT NULL CHECK (item IN ('제동장치','출입문','대차·차륜','전력·팬터그래프','신호수신(ATP)','객실 공조')),
  base_status TEXT NOT NULL DEFAULT 'ok' CHECK (base_status IN ('ok','warn','bad')),
  PRIMARY KEY (train_id, item)
);

CREATE TABLE fault_templates (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fault_type       TEXT NOT NULL CHECK (fault_type IN ('signal','track','weather','delay')),
  sub_type         TEXT,
  name             TEXT NOT NULL,
  code_prefix      TEXT NOT NULL,
  default_severity TEXT NOT NULL CHECK (default_severity IN ('주의','위험','심각')),
  summary_tpl      TEXT NOT NULL,
  delay_min        INTEGER NOT NULL,
  delay_max        INTEGER NOT NULL,
  UNIQUE (fault_type, sub_type)
);
CREATE TABLE template_causes (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id BIGINT NOT NULL REFERENCES fault_templates(id) ON DELETE CASCADE,
  label       TEXT NOT NULL,
  base_prob   INTEGER NOT NULL CHECK (base_prob BETWEEN 0 AND 100)
);
CREATE TABLE template_actions (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id BIGINT NOT NULL REFERENCES fault_templates(id) ON DELETE CASCADE,
  seq         INTEGER NOT NULL,
  label       TEXT NOT NULL
);

CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  display_name  TEXT NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('viewer','operator','admin')),
  is_active     INTEGER NOT NULL DEFAULT 1,
  created_at    TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'Asia/Seoul', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE faults (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                TEXT NOT NULL UNIQUE,
  fault_type          TEXT NOT NULL CHECK (fault_type IN ('signal','track','weather','delay')),
  sub_type            TEXT,
  line_id             TEXT NOT NULL REFERENCES lines(id),
  target_train_id     BIGINT REFERENCES trains(id),
  location_text       TEXT NOT NULL,
  severity            TEXT NOT NULL CHECK (severity IN ('주의','위험','심각')),
  phase               TEXT NOT NULL CHECK (phase IN ('detected','analyzing','analyzed','recovering','resolved')),
  summary             TEXT,
  confidence          INTEGER,
  impact_trains       INTEGER,
  expected_delay_min  INTEGER,
  source              TEXT NOT NULL DEFAULT 'manual' CHECK (source IN ('manual','demo')),
  created_by          BIGINT REFERENCES users(id),
  recovered_by        BIGINT REFERENCES users(id),
  created_sim         INTEGER NOT NULL,
  created_at          TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'Asia/Seoul', 'YYYY-MM-DD HH24:MI:SS'),
  analysis_started_at TEXT,
  analyzed_at         TEXT,
  recovering_at       TEXT,
  resolved_at         TEXT,
  ana_epoch           DOUBLE PRECISION,
  rec_epoch           DOUBLE PRECISION
);
CREATE INDEX idx_faults_phase ON faults(phase);

CREATE TABLE fault_segments (
  fault_id   BIGINT NOT NULL REFERENCES faults(id) ON DELETE CASCADE,
  segment_id BIGINT NOT NULL REFERENCES segments(id),
  level      TEXT NOT NULL CHECK (level IN ('warn','danger')),
  PRIMARY KEY (fault_id, segment_id)
);
CREATE TABLE fault_causes (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fault_id    BIGINT NOT NULL REFERENCES faults(id) ON DELETE CASCADE,
  rank        INTEGER NOT NULL,
  label       TEXT NOT NULL,
  probability INTEGER NOT NULL
);
CREATE TABLE fault_actions (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fault_id BIGINT NOT NULL REFERENCES faults(id) ON DELETE CASCADE,
  seq      INTEGER NOT NULL,
  label    TEXT NOT NULL,
  done     INTEGER NOT NULL DEFAULT 0 CHECK (done IN (0,1)),
  done_at  TEXT,
  done_by  BIGINT REFERENCES users(id),
  UNIQUE (fault_id, seq)
);
CREATE TABLE fault_affected_trains (
  fault_id BIGINT NOT NULL REFERENCES faults(id) ON DELETE CASCADE,
  train_id BIGINT NOT NULL REFERENCES trains(id),
  PRIMARY KEY (fault_id, train_id)
);

CREATE TABLE event_logs (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sim_time   INTEGER NOT NULL,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'Asia/Seoul', 'YYYY-MM-DD HH24:MI:SS'),
  category   TEXT NOT NULL CHECK (category IN ('info','ok','warn','danger','ai','action','audit')),
  message    TEXT NOT NULL,
  fault_id   BIGINT REFERENCES faults(id) ON DELETE SET NULL,
  train_id   BIGINT REFERENCES trains(id) ON DELETE SET NULL,
  user_id    BIGINT REFERENCES users(id)
);
CREATE INDEX idx_events_cat ON event_logs(category, id);
CREATE INDEX idx_events_created ON event_logs(created_at);
CREATE INDEX idx_events_fault ON event_logs(fault_id);

CREATE TABLE kpi_snapshots (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sim_time       INTEGER NOT NULL,
  created_at     TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'Asia/Seoul', 'YYYY-MM-DD HH24:MI:SS'),
  total_trains   INTEGER NOT NULL,
  on_time_rate   DOUBLE PRECISION NOT NULL,
  safety_index   DOUBLE PRECISION NOT NULL,
  delayed_trains INTEGER NOT NULL,
  active_faults  INTEGER NOT NULL
);
CREATE INDEX idx_kpi_created ON kpi_snapshots(created_at);

CREATE TABLE sim_state (
  id             INTEGER PRIMARY KEY CHECK (id = 1),
  sim_time       DOUBLE PRECISION NOT NULL DEFAULT 28800,
  speed_mul      INTEGER NOT NULL DEFAULT 1 CHECK (speed_mul IN (1,2,5)),
  paused         INTEGER NOT NULL DEFAULT 0,
  demo_active    INTEGER NOT NULL DEFAULT 0,
  demo_elapsed   DOUBLE PRECISION NOT NULL DEFAULT 0,
  fault_seq      INTEGER NOT NULL DEFAULT 0,
  last_real      DOUBLE PRECISION NOT NULL DEFAULT 0,
  last_hist_real DOUBLE PRECISION NOT NULL DEFAULT 0,
  last_kpi_real  DOUBLE PRECISION NOT NULL DEFAULT 0,
  fault_ver      INTEGER NOT NULL DEFAULT 0,
  demo_user_id   BIGINT,
  demo_result    TEXT,
  updated_at     TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'Asia/Seoul', 'YYYY-MM-DD HH24:MI:SS')
);

-- Supabase REST(anon/authenticated)로의 접근 차단: RLS 를 켜고 정책은 만들지 않는다.
