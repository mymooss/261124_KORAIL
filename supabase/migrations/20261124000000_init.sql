ALTER TABLE trains ENABLE ROW LEVEL SECURITY;
ALTER TABLE train_inspections ENABLE ROW LEVEL SECURITY;
ALTER TABLE fault_templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE template_causes ENABLE ROW LEVEL SECURITY;
ALTER TABLE template_actions ENABLE ROW LEVEL SECURITY;
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE faults ENABLE ROW LEVEL SECURITY;
ALTER TABLE fault_segments ENABLE ROW LEVEL SECURITY;
ALTER TABLE fault_causes ENABLE ROW LEVEL SECURITY;
